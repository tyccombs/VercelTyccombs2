// Regenerates the gear list in portfolio-site/gear.html from the Obsidian note
// "Ouch Website/Gear List.md" (the single source of truth). Run: node site-src/build-gear.mjs
// Only the part between <!-- GEAR:START --> and <!-- GEAR:END --> is rewritten.
// Reads the "# Current Gear" section: each "## Category" with a table of
// Item | Qty | Description | Value | Day Rate | Site. Rows with Site = no are skipped.
// Day Rate is not published (yet). Pass a different note path as the first argument if needed.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { homedir } from 'node:os';

const here = dirname(fileURLToPath(import.meta.url));
const pagePath = join(here, '..', 'portfolio-site', 'gear.html');
const notePath = process.argv[2] || join(homedir(), 'Documents/Coding/OBSIDIAN/VAULT/Ouch Website/Gear List.md');

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const money = (n) => '$' + n.toLocaleString('en-US');
const parseMoney = (s, where) => {
  const n = Number(String(s).replace(/[$,\s]/g, ''));
  if (!Number.isFinite(n) || String(s).trim() === '') throw new Error(`Bad value "${s}" (${where})`);
  return n;
};

// --- parse the note ---
const lines = readFileSync(notePath, 'utf8').split('\n');
const start = lines.findIndex((l) => /^#\s+Current Gear\s*$/.test(l));
if (start < 0) throw new Error('No "# Current Gear" heading in ' + notePath);
const categories = [];
let cat = null;
let header = null;
for (let i = start + 1; i < lines.length; i++) {
  const l = lines[i].trim();
  if (/^#\s/.test(l)) break; // next top-level section (e.g. "# To Order")
  const h = l.match(/^##\s+(.+)$/);
  if (h) { cat = { name: h[1].trim(), items: [] }; categories.push(cat); header = null; continue; }
  if (!l.startsWith('|') || !cat) continue;
  const cells = l.replace(/^\|/, '').replace(/\|$/, '').split('|').map((c) => c.trim());
  if (cells.every((c) => /^:?-+:?$/.test(c))) continue; // separator row
  if (!header) { header = cells.map((c) => c.toLowerCase()); continue; }
  const row = Object.fromEntries(header.map((k, j) => [k, cells[j] ?? '']));
  if (!row.item) continue;
  if ((row.site || 'yes').toLowerCase() === 'no') continue;
  const where = `${cat.name} / ${row.item}, line ${i + 1}`;
  cat.items.push({
    name: row.item,
    qty: Number(row.qty || 1) || 1,
    desc: row.description || '',
    value: parseMoney(row.value, where),
  });
}
const shown = categories.filter((c) => c.items.length);
if (!shown.length) throw new Error('No gear rows found under "# Current Gear"');
const total = shown.flatMap((c) => c.items).reduce((s, it) => s + it.value, 0);

// --- render ---
const itemHtml = (it) => `      <div class="py-4 grid md:grid-cols-[1fr_auto] gap-1 md:gap-8 items-baseline">
        <div>
          <p class="font-semibold text-base">${esc(it.name)}${it.qty > 1 ? ` <span class="text-slate-400 text-sm font-bold ml-1">×${it.qty}</span>` : ''}</p>${it.desc ? `
          <p class="text-slate-500 dark:text-slate-400 text-sm">${esc(it.desc)}</p>` : ''}
        </div>
        <p class="text-slate-600 dark:text-slate-300 text-sm font-medium tabular-nums md:text-right">${money(it.value)}</p>
      </div>`;

const sectionHtml = (c) => `  <!-- ${esc(c.name)} -->
  <section class="mb-14">
    <div class="flex items-baseline justify-between border-b border-slate-200 dark:border-slate-700 pb-3 mb-2">
      <h2 class="text-slate-100 tracking-[0.3em] uppercase text-sm">${esc(c.name)}</h2>
      <span class="text-slate-500 dark:text-slate-400 text-[10px] uppercase tracking-widest font-bold">Replacement Value</span>
    </div>
    <div class="divide-y divide-slate-200 dark:divide-slate-800">
${c.items.map(itemHtml).join('\n')}
    </div>
  </section>`;

const asOf = new Date().toLocaleString('en-US', { month: 'long', year: 'numeric' });
const block = `<!-- GEAR:START (generated by site-src/build-gear.mjs from the Obsidian "Gear List" note; do not hand-edit) -->

${shown.map(sectionHtml).join('\n\n')}

  <!-- Total -->
  <div class="border-t-2 border-slate-300 dark:border-slate-600 pt-6 mt-16 flex items-baseline justify-between">
    <span class="uppercase tracking-[0.3em] text-sm font-bold text-slate-500 dark:text-slate-400">Total Kit Replacement Value</span>
    <span class="text-3xl md:text-4xl font-black text-white tabular-nums">${money(total)}</span>
  </div>
  <p class="text-slate-500 dark:text-slate-400 text-xs mt-4 leading-relaxed max-w-2xl">
    Replacement values reflect current retail pricing and are provided for production insurance and
    certificate-of-insurance purposes. Kit list current as of ${asOf}.
  </p>
  <!-- GEAR:END -->`;

const page = readFileSync(pagePath, 'utf8');
const re = /<!-- GEAR:START[\s\S]*?<!-- GEAR:END -->/;
if (!re.test(page)) throw new Error('gear.html has no GEAR:START / GEAR:END markers');
const next = page.replace(re, block);
if (next === page) { console.log('gear.html already up to date'); process.exit(0); }
writeFileSync(pagePath, next);
console.log(`gear.html updated: ${shown.length} categories, ${shown.reduce((s, c) => s + c.items.length, 0)} items, total ${money(total)}`);
